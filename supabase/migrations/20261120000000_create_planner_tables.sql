-- State used by the Telegram day-planner bot.
create table if not exists public.bot_owner (
  id integer primary key default 1 check (id = 1),
  chat_id bigint not null,
  claimed_at timestamptz not null default now(),
  first_name text
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_chat_id_created_at_idx
  on public.chat_messages (chat_id, created_at desc);

create table if not exists public.processed_updates (
  update_id bigint primary key,
  created_at timestamptz not null default now()
);

-- The application accesses these tables through its server-only service-role client.
alter table public.bot_owner enable row level security;
alter table public.chat_messages enable row level security;
alter table public.processed_updates enable row level security;
